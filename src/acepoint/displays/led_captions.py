Frame = tuple[int, ...]          # 一帧：每列一个整数，第 r 位 = 第 r 行


def _columns(rows: tuple[str, ...]) -> list[int]:
    width = max(len(r) for r in rows)
    return [sum(1 << y for y, row in enumerate(rows) if x < len(row) and row[x] == "#")
            for x in range(width)]


_FONT = {ch: _columns(rows) for ch, rows in _FONT_ROWS.items()}
_ICONS = {name: (_columns(a), _columns(b) if b else None) for name, (a, b) in _ICON_ROWS.items()}


def _tokens(page: str) -> list[str]:
    out, i = [], 0
    while i < len(page):
        if page[i] == "{":
            end = page.index("}", i)
            out.append(page[i:end + 1])
            i = end + 1
        else:
            out.append(page[i])
            i += 1
    return out


def render_page(page: str, frame: int, width: int = 32) -> Frame:
    """把一页排成 width 列（居中）。frame 选图标的第几帧（0/1）。"""
    columns: list[int] = []
    for token in _tokens(page):
        if token.startswith("{"):
            first, second = _ICONS[token[1:-1]]
            glyph = second if frame and second else first
        else:
            glyph = _FONT[token]
        if columns:
            columns.append(0)                       # 字与字之间空一列
        columns.extend(glyph)
    if len(columns) > width:
        raise ValueError(f"page {page!r} is {len(columns)} px, wider than {width}")
    pad = (width - len(columns)) // 2
    return tuple([0] * pad + columns + [0] * (width - pad - len(columns)))


def pick_scene(event: str, rng: random.Random, previous: int | None = None):
    """挑一种画面，返回 (下标, 页列表)；没有对应场景返回 None。尽量不连着重复同一种。"""
    options = SCENES.get(event)
    if not options:
        return None
    choices = [i for i in range(len(options)) if i != previous] or list(range(len(options)))
    index = rng.choice(choices)
    return index, options[index]


def scene_frame(pages: tuple[str, ...], elapsed: float, width: int = 32) -> Frame:
    """场景开始 elapsed 秒后该显示的那一帧：按页轮换，页内图标两帧交替。"""
    page = pages[int(elapsed / PAGE_SECONDS) % len(pages)]
    return render_page(page, int(elapsed / FRAME_SECONDS) % 2, width)
